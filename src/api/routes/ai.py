logger = logging.getLogger(__name__)
router = APIRouter(prefix="/api/ai", tags=["AI & Quantitative Intelligence"])

@router.get("/screener/focus", response_model=List[ScreenerCandidateItem])
def get_focus_screener_watchlist(
    services: ServiceContainer = Depends(get_services)
):
    """
    Returns today's 09:08 AM Pre-Market AI Focus Watchlist generated by Model 0.
    """
    watchlist = services.strategy_runner.focus_watchlist
    if not watchlist:
        # If watchlist hasn't been generated in memory yet today, generate preview from Gold Lakehouse
        try:
            from src.models.data_splitter import DataSplitter
            splitter = DataSplitter()
            _, test_df0 = splitter.load_dataset(0, max_symbols=300, min_turnover_cr=2.0)
            latest_day = test_df0["date"].max()
            day_df = test_df0.filter(pl.col("date") == latest_day)
            watchlist = services.strategy_runner.run_premarket_screener(day_df)
        except Exception as e:
            logger.warning(f"Could not compute preview watchlist: {e}")

    items = []
    for idx, c in enumerate(watchlist, 1):
        items.append(ScreenerCandidateItem(
            rank=idx,
            symbol=c.symbol,
            current_price=round(c.current_price, 2),
            rank_score=round(c.rank_score, 4),
            action="STRONG_BUY" if c.rank_score > 0.05 else "BUY",
            confidence_pct=round(min(95.0, max(55.0, 50.0 + c.rank_score * 300.0)), 1),
            turnover_cr=round(c.calmar_ratio * 10.0, 2)
        ))

    return items

@router.get("/forecast/corridor/{symbol}", response_model=CorridorForecast)
def get_price_corridor(
    symbol: str,
    services: ServiceContainer = Depends(get_services)
):
    """
    Returns Model 3 Multi-Horizon Probabilistic Price Corridor:
    P05 (Stop-Loss Floor), P25 (Lower Range), P50 (Baseline), P75 (Target 1), Q90 (Runner Ceiling).
    """
    sym = symbol.strip().upper()
    runner = services.strategy_runner

    # Read latest Gold features for this symbol
    p3_file = settings.DATA_DIR / "lakehouse" / "gold" / "features_price_corridor" / f"{sym}.parquet"
    if not p3_file.exists():
        raise HTTPException(status_code=404, detail=f"Price corridor model features not found for {sym}")

    try:
        df3 = pl.read_parquet(p3_file)
        if len(df3) == 0:
            raise HTTPException(status_code=404, detail=f"No feature records for {sym}")

        last_row = df3.tail(1).to_dicts()[0]
        cur_px = float(last_row.get("close", 100.0))

        # Get latest price quote if available
        q = services.redis_manager.get_quote("NSE", sym)
        if q and float(q.get("ltp") or 0) > 0:
            cur_px = float(q.get("ltp"))

        m3_feats = runner.registry["models"]["model3"]["features"]
        x3 = np.array([[last_row.get(k, 0.0) for k in m3_feats]], dtype=np.float32)

        p05 = float(runner.models["model3"]["p05"].predict(x3)[0])
        p25 = float(runner.models["model3"]["p25"].predict(x3)[0])
        p50 = float(runner.models["model3"]["p50"].predict(x3)[0])
        p75 = float(runner.models["model3"]["p75"].predict(x3)[0])

        m1_feats = runner.registry["models"]["model1"]["features"]
        x1 = np.array([[last_row.get(k, 0.0) for k in m1_feats]], dtype=np.float32)
        q90 = float(runner.models["model1"]["q90"].predict(x1)[0])

        # Enforce physical price monotonicity
        p05 = min(p05, cur_px * 0.98)
        p25 = max(p05 * 1.01, min(p25, cur_px))
        p50 = max(p25, p50)
        p75 = max(p50, p75)
        q90 = max(p75 * 1.02, q90)

        width_pct = round(((q90 - p05) / cur_px) * 100.0, 2)
        downside_dist = max(cur_px - p05, 0.1)
        upside_dist = max(p75 - cur_px, 0.1)
        asymmetry = round(upside_dist / downside_dist, 2)

        return CorridorForecast(
            symbol=sym,
            current_price=round(cur_px, 2),
            p05_floor=round(p05, 2),
            p25_lower=round(p25, 2),
            p50_median=round(p50, 2),
            p75_target1=round(p75, 2),
            q90_runner=round(q90, 2),
            corridor_width_pct=width_pct,
            asymmetry_ratio=asymmetry
        )

    except Exception as e:
        logger.error(f"Error computing corridor for {sym}: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=str(e))

@router.get("/signal/{symbol}", response_model=AISignalResponse)
def get_ai_diagnostic_signal(
    symbol: str,
    services: ServiceContainer = Depends(get_services)
):
    """
    Returns full 5-tier institutional diagnostic AI signal:
    Model 4 Calibrated Action, Directional Confidence %, Dynamic Stop Loss, Target 1, Target 2.
    """
    sym = symbol.strip().upper()
    runner = services.strategy_runner

    # Check Model 4 features in Gold
    p4_file = settings.DATA_DIR / "lakehouse" / "gold" / "features_stock_action_classifier" / f"{sym}.parquet"
    if not p4_file.exists():
        raise HTTPException(status_code=404, detail=f"Stock action features not found for {sym}")

    try:
        df4 = pl.read_parquet(p4_file)
        if len(df4) == 0:
            raise HTTPException(status_code=404, detail=f"No feature records for {sym}")

        last_row = df4.tail(1).to_dicts()[0]
        cur_px = float(last_row.get("close", 100.0))

        q = services.redis_manager.get_quote("NSE", sym)
        if q and float(q.get("ltp") or 0) > 0:
            cur_px = float(q.get("ltp"))

        m4_feats = runner.registry["models"]["model4"]["features"]
        x4 = np.array([[last_row.get(k, 0.0) for k in m4_feats]], dtype=np.float32)

        # Calibrated probability distribution
        probs = runner.models["model4"].predict_proba(x4)[0]
        classes = runner.models["model4"].classes_
        class_prob_map = {cls_name: prob for cls_name, prob in zip(classes, probs)}

        prob_buy = class_prob_map.get("BUY", 0.0)
        prob_strong_buy = class_prob_map.get("STRONG_BUY", 0.0)
        prob_sell = class_prob_map.get("SELL", 0.0)
        prob_strong_sell = class_prob_map.get("STRONG_SELL", 0.0)

        directional_denom = prob_buy + prob_strong_buy + prob_sell + prob_strong_sell
        if directional_denom > 0:
            bullish_ratio = (prob_buy + prob_strong_buy) / directional_denom
        else:
            bullish_ratio = 0.5

        if bullish_ratio >= 0.65:
            action = "STRONG_BUY"
            confidence = bullish_ratio
        elif bullish_ratio >= 0.55:
            action = "BUY"
            confidence = bullish_ratio
        elif bullish_ratio <= 0.35:
            action = "STRONG_SELL"
            confidence = 1.0 - bullish_ratio
        elif bullish_ratio <= 0.45:
            action = "SELL"
            confidence = 1.0 - bullish_ratio
        else:
            action = "HOLD"
            confidence = class_prob_map.get("HOLD", 0.5)

        # Dynamic Stop & Targets from corridor
        corridor = get_price_corridor(sym, services)
        rr_ratio = round(abs(corridor.p75_target1 - cur_px) / max(abs(cur_px - corridor.p05_floor), 0.1), 2)

        return AISignalResponse(
            symbol=sym,
            action=action,
            confidence_pct=round(confidence * 100.0, 1),
            current_price=round(cur_px, 2),
            recommended_entry=round(cur_px, 2),
            dynamic_stop_loss=corridor.p05_floor,
            target_1=corridor.p75_target1,
            target_2=corridor.q90_runner,
            risk_reward_ratio=rr_ratio,
            generated_at=datetime.now(timezone.utc).isoformat()
        )

    except Exception as e:
        logger.error(f"Error computing AI signal for {sym}: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=str(e))
